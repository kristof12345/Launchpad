   static let gridItems = "LaunchpadAppGridItems"
   
   /// Key for storing paths of hidden applications
   static let hiddenApps = "LaunchpadHiddenApps"
   
   /// Key for storing application settings
   static let settings = "LaunchpadSettings"
}
